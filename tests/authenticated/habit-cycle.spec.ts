import { randomUUID } from "node:crypto";
import { test, expect, localSql } from "./fixtures";
import { withPeer } from "./peer";
import { mkdirSync } from "node:fs";
import path from "node:path";

test("ciclo administrativo preserva momentos e exige novo aceite para novos termos", async ({ page, account }, testInfo) => {
  test.setTimeout(150_000);
  page.setDefaultTimeout(15_000);
  const nucleus = randomUUID();
  const gallery = process.env.NOS_ADMIN_GALLERY;
  const capture = async (id: number) => { if (gallery) { mkdirSync(gallery, { recursive: true }); await page.evaluate(() => document.fonts.ready); await page.screenshot({ path: path.join(gallery, `app-${id}-${testInfo.project.name}.png`), fullPage: true }); } };
  await withPeer(page, async peer => {
    try {
      localSql(`insert into public.nuclei(id,type,name,purpose,created_by) values('${nucleus}','familia','Ciclo administrativo','Cuidar','${account.id}'); insert into public.nucleus_members(nucleus_id,user_id,role) values('${nucleus}','${account.id}','admin'),('${nucleus}','${peer.id}','member');`);
      const hub = `/nucleos/${nucleus}/acordos`;
      await page.goto(hub);
      await page.getByRole("button", { name: "Nova proposta", exact: true }).click();
      await page.getByLabel("O que vamos fazer?").fill("Conversar juntos");
      await page.getByLabel("Como será?").fill("Sem distrações");
      await page.getByLabel("Quando?", { exact: true }).fill("Noite");
      await page.getByLabel("Com que frequência?").fill("Diária");
      await page.getByLabel("Duração do teste (dias)").fill("7");
      await capture(18);
      await page.getByRole("button", { name: "Conferir proposta", exact: true }).click();
      await capture(22);
      expect(localSql(`select count(*) from public.nucleus_agreements where nucleus_id='${nucleus}'`).trim()).toBe("0");
      await page.getByRole("button", { name: "Enviar proposta", exact: true }).click();
      await expect(page).toHaveURL(/resultado=proposta/);
      await capture(23);
      const habit = localSql(`select id from public.nucleus_agreements where nucleus_id='${nucleus}'`).trim();
      expect(localSql(`select count(*) from public.nucleus_agreement_participants where agreement_id='${habit}' and response='accepted'`).trim()).toBe("0");
      await page.getByRole("button", { name: /Conversar juntos/ }).click();
      await page.getByRole("button", { name: "Aceitar proposta", exact: true }).click();
      await expect(page).toHaveURL(/resultado=resposta/);
      await page.getByRole("button", { name: /Conversar juntos/ }).click();
      await page.getByRole("button", { name: "Administrar acordo", exact: true }).click();
      await page.getByLabel("Iniciar o teste; cada pessoa decide se participa.").check();
      await page.getByRole("button", { name: "Iniciar teste", exact: true }).click();
      await expect(page).toHaveURL(/resultado=gestao/);
      await peer.page.goto(`http://127.0.0.1:3200${hub}`);
      await peer.page.getByRole("button", { name: /Conversar juntos/ }).click();
      await expect(peer.page.getByRole("button", { name: "Ativar acordo", exact: true })).toHaveCount(0);
      await expect(peer.page.getByRole("button", { name: "Administrar acordo", exact: true })).toHaveCount(0);
      await peer.page.getByRole("button", { name: "Aceitar proposta", exact: true }).click();
      await expect(peer.page).toHaveURL(/resultado=resposta/);
      const base = `${hub}/${habit}`;
      await page.goto(base);
      await page.getByRole("button", { name: "Registrar momento", exact: true }).click();
      await page.getByText("Bem", { exact: true }).click();
      await expect(page.getByLabel("Bem", { exact: true })).toBeChecked();
      await page.getByRole("textbox").fill("Vivência preservada");
      await page.getByRole("button", { name: "Salvar momento", exact: true }).click();
      await expect(page.getByText("Vivência preservada", { exact: true })).toBeVisible();
      await capture(24);
      await page.goto(`${base}/revisar`);
      await page.getByRole("button", { name: "Alterar termos", exact: true }).click();
      await page.getByLabel("Publicar nova versão e solicitar novo aceite a cada participante.").check();
      await page.getByRole("button", { name: "Publicar novos termos", exact: true }).click();
      await expect(page.getByRole("alert").filter({ hasText: "Os termos não mudaram" })).toBeVisible();
      await page.getByLabel("Quando?", { exact: true }).fill("Manhã");
      await capture(31);
      await page.getByLabel("Publicar nova versão e solicitar novo aceite a cada participante.").check();
      await page.getByRole("button", { name: "Publicar novos termos", exact: true }).click();
      await expect(page).toHaveURL(/resultado=gestao/);
      expect((await peer.client.rpc("record_nucleus_habit_moment", { target_nucleus: nucleus, target_agreement: habit, moment_mood: "good", moment_note: "Aceite antigo" })).error).toBeTruthy();
      expect((await peer.client.rpc("respond_nucleus_agreement", { target_agreement: habit, agreement_response: "accepted", expected_terms_version: 1 })).error).toBeTruthy();
      await peer.page.goto(`http://127.0.0.1:3200${hub}`);
      await peer.page.getByRole("button", { name: /Conversar juntos/ }).click();
      await peer.page.getByRole("button", { name: "Aceitar proposta", exact: true }).click();
      await expect(peer.page).toHaveURL(/resultado=resposta/);
      await page.goto(`${base}/confirmar`);
      await expect(page.getByRole("heading", { name: "Período e administração do hábito", exact: true })).toBeVisible();
      await capture(28);
      await page.goto(hub);
      await page.getByRole("button", { name: /Conversar juntos/ }).click();
      await page.getByRole("button", { name: "Administrar acordo", exact: true }).click();
      await page.getByLabel("Concluir o teste e manter o acordo ativo com participação individual.").check();
      await page.getByRole("button", { name: "Ativar acordo", exact: true }).click();
      await expect(page).toHaveURL(/resultado=gestao/);
      await page.getByRole("button", { name: /Conversar juntos/ }).click();
      await page.getByRole("button", { name: "Administrar acordo", exact: true }).click();
      await page.getByLabel("Encerrar o acordo e impedir novos momentos; o histórico permanecerá.").check();
      await page.getByRole("button", { name: "Encerrar acordo", exact: true }).click();
      await expect(page).toHaveURL(/resultado=gestao/);
      await page.goto(base);
      await expect(page.getByText("Vivência preservada", { exact: true })).toBeVisible();
      await expect(page.getByRole("link", { name: "Registrar momento", exact: true })).toHaveCount(0);
      await expect(page.getByRole("button", { name: "Registrar momento", exact: true })).toHaveCount(0);
      await page.goto(`${base}/revisar`);
      await expect(page.getByRole("heading", { name: /Versão 1/ })).toBeVisible();
      await expect(page.getByRole("heading", { name: /Versão 2/ })).toBeVisible();
      await capture(33);
    } finally { localSql(`delete from public.nuclei where id='${nucleus}';`); }
  });
});
